SELECT 'MW' AS SOURCE_CD,
       MW_ID AS OBJECT_ID,
       PRODUCT_NAME AS OBJECT_NAME,
       ASSET_ID AS ASSET_ID,
       EOL_DATE AS EOL_DATE
  FROM TB_IF_MW_INSTALL_PILOT
