       DB_ID AS OBJECT_ID,
       DB_NAME AS OBJECT_NAME,
       ASSET_ID AS ASSET_ID,
       EOL_DATE AS EOL_DATE
  FROM TB_IF_DB_INSTANCE_PILOT
 WHERE EOL_DATE IS NOT NULL;

