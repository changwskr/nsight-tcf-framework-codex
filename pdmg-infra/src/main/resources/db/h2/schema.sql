       TRIM(COALESCE(OS_NAME, '') || CASE WHEN OS_VERSION IS NULL OR OS_VERSION = '' THEN '' ELSE ' ' || OS_VERSION END) AS OBJECT_NAME,
       ASSET_ID AS ASSET_ID,
       OS_EOL_DATE AS EOL_DATE
