-- INF-940 표10 TCO 비교 (cost_snapshot 집계, 기본 5Y)
CREATE VIEW V_IF_PROPOSAL_TCO AS
SELECT C.TARGET_TYPE_CD AS TARGET_TYPE_CD,
       C.TARGET_ID AS TARGET_ID,
       C.PERIOD_YM AS PERIOD_YM,
       MAX(C.CURRENCY_CD) AS CURRENCY_CD,
       5 AS YEARS,
       SUM(CASE WHEN C.SCENARIO_CD = 'ASIS' THEN C.AMOUNT ELSE 0 END) AS ASIS_ANNUAL,
       SUM(CASE WHEN C.SCENARIO_CD = 'TOBE' THEN C.AMOUNT ELSE 0 END) AS TOBE_ANNUAL,
       SUM(CASE WHEN C.SCENARIO_CD = 'MIG' THEN C.AMOUNT ELSE 0 END) AS MIGRATION_ONCE,
       SUM(CASE WHEN C.SCENARIO_CD = 'ASIS' THEN C.AMOUNT ELSE 0 END) * 5 AS ASIS_TCO,
       SUM(CASE WHEN C.SCENARIO_CD = 'TOBE' THEN C.AMOUNT ELSE 0 END) * 5
         + SUM(CASE WHEN C.SCENARIO_CD = 'MIG' THEN C.AMOUNT ELSE 0 END) AS TOBE_TCO,
       (SUM(CASE WHEN C.SCENARIO_CD = 'ASIS' THEN C.AMOUNT ELSE 0 END) * 5)
         - (SUM(CASE WHEN C.SCENARIO_CD = 'TOBE' THEN C.AMOUNT ELSE 0 END) * 5
            + SUM(CASE WHEN C.SCENARIO_CD = 'MIG' THEN C.AMOUNT ELSE 0 END)) AS DELTA_TCO,
       SUM(CASE WHEN C.SCENARIO_CD = 'ASIS' AND C.COST_TYPE_CD = 'HW' THEN C.AMOUNT ELSE 0 END) AS ASIS_HW,
       SUM(CASE WHEN C.SCENARIO_CD = 'ASIS' AND C.COST_TYPE_CD = 'CLOUD' THEN C.AMOUNT ELSE 0 END) AS ASIS_CLOUD,
       SUM(CASE WHEN C.SCENARIO_CD = 'ASIS' AND C.COST_TYPE_CD = 'MW' THEN C.AMOUNT ELSE 0 END) AS ASIS_MW,
       SUM(CASE WHEN C.SCENARIO_CD = 'ASIS' AND C.COST_TYPE_CD = 'DB' THEN C.AMOUNT ELSE 0 END) AS ASIS_DB,
       SUM(CASE WHEN C.SCENARIO_CD = 'ASIS' AND C.COST_TYPE_CD = 'OPS' THEN C.AMOUNT ELSE 0 END) AS ASIS_OPS,
       SUM(CASE WHEN C.SCENARIO_CD = 'TOBE' AND C.COST_TYPE_CD = 'HW' THEN C.AMOUNT ELSE 0 END) AS TOBE_HW,
       SUM(CASE WHEN C.SCENARIO_CD = 'TOBE' AND C.COST_TYPE_CD = 'CLOUD' THEN C.AMOUNT ELSE 0 END) AS TOBE_CLOUD,
       SUM(CASE WHEN C.SCENARIO_CD = 'TOBE' AND C.COST_TYPE_CD = 'MW' THEN C.AMOUNT ELSE 0 END) AS TOBE_MW,
       SUM(CASE WHEN C.SCENARIO_CD = 'TOBE' AND C.COST_TYPE_CD = 'DB' THEN C.AMOUNT ELSE 0 END) AS TOBE_DB,
       SUM(CASE WHEN C.SCENARIO_CD = 'TOBE' AND C.COST_TYPE_CD = 'OPS' THEN C.AMOUNT ELSE 0 END) AS TOBE_OPS
  FROM TB_IF_COST_PILOT C
 GROUP BY C.TARGET_TYPE_CD, C.TARGET_ID, C.PERIOD_YM;

-- INF-940 서버 인벤토리 (파일럿 서버 + Primary IP)
