-- INF-940 서버군 용량 (Peak Snapshot 조인)
CREATE VIEW V_IF_SERVER_GROUP_CAPACITY AS
SELECT G.GROUP_ID AS GROUP_ID,
       G.GROUP_NAME AS GROUP_NAME,
       G.SYSTEM_ID AS SYSTEM_ID,
       G.TECH_ROLE_CD AS TECH_ROLE_CD,
       G.ENV_CD AS ENV_CD,
       G.TIER_CD AS TIER_CD,
       G.STATUS_CD AS STATUS_CD,
       G.ACTIVE_NODES AS ACTIVE_NODES,
       G.STANDBY_NODES AS STANDBY_NODES,
       G.DR_NODES AS DR_NODES,
       C.TPS AS PEAK_TPS,
       C.CPU_PCT AS PEAK_CPU_PCT,
       C.MEM_PCT AS PEAK_MEM_PCT,
       C.RESP_P95_MS AS PEAK_RESP_P95_MS
  FROM TB_IF_SERVER_GROUP_PILOT G
  LEFT JOIN TB_IF_CAPACITY_PILOT C
    ON C.TARGET_TYPE_CD = 'GROUP'
   AND C.TARGET_ID = G.GROUP_ID
   AND C.METRIC_SCOPE_CD = 'PEAK';
